def shots_pass(season, players, agg, live=False):
    """`agg` = ext_shots counts {pid: {"z","a","d","n"}} for the season."""
    if not agg:
        return 0
    wins = list(C.WINDOWS.keys()) if live else ["season"]
    poss = _poss_map(None, season)
    n = 0
    for p in players:
        a = agg.get(p["id"])
        if not a or not a.get("n"):
            continue
        z, fam = a.get("z", {}), a.get("a", {})
        fga = a["n"]
        ra, pnt, mid = z.get("ra", [0, 0]), z.get("pnt", [0, 0]), z.get("mid", [0, 0])
        c3, ab3 = z.get("c3", [0, 0]), z.get("ab3", [0, 0])
        three = c3[0] + ab3[0]
        _put_all(p, "rimfreq", _pct(ra[0], fga), fga, wins)
        if ra[0]:
            _put_all(p, "rimfg", _pct(ra[1], ra[0]), ra[0], wins)
        _put_all(p, "pntfreq", _pct(pnt[0], fga), fga, wins)
        if pnt[0]:
            _put_all(p, "pntfg", _pct(pnt[1], pnt[0]), pnt[0], wins)
        _put_all(p, "midfreq", _pct(mid[0], fga), fga, wins)
        if mid[0]:
            _put_all(p, "midfg", _pct(mid[1], mid[0]), mid[0], wins)
        if three:
            _put_all(p, "c3rate", _pct(c3[0], three), three, wins)
        if c3[0]:
            _put_all(p, "c3pct", _pct(c3[1], c3[0]), c3[0], wins)
        if ab3[0]:
            _put_all(p, "ab3pct", _pct(ab3[1], ab3[0]), ab3[0], wins)
        _put_all(p, "sdist", a["d"] / fga, fga, wins)
        ps = poss.get(p["id"])
        dk = fam.get("dunk", [0, 0])
        pb = fam.get("putback", [0, 0])
        _put_all(p, "dunk75", _per75(dk[1], ps), ps, wins)
        _put_all(p, "pb75", _per75(pb[0], ps), ps, wins)
        p["sm"] = {k: v for k, v in fam.items() if v and v[0]}
        n += 1
    return n


# ===================================================================== ESPN play-by-play
def pbp_pass(season, players, counts, live=False):
    """`counts` = {nba id: ext_pbp counters} for the season (already mapped to NBA ids)."""
    if not counts:
        return 0
    wins = list(C.WINDOWS.keys()) if live else ["season"]
    n = 0
    for p in players:
        c = counts.get(p["id"])
        if not c:
            continue
        g = lambda k: c.get(k, 0.0)  # noqa: E731
        gp = g("gp")
        if g("rim_fgm"):
            _put_all(p, "ast_rim", _pct(g("rim_ast"), g("rim_fgm")), g("rim_fgm"), wins)
        if g("tov_n"):
            _put_all(p, "livetov", _pct(g("tov_live"), g("tov_n")), g("tov_n"), wins)
        fga = g("tr_fga") + g("hc_fga")
        if fga:
            _put_all(p, "trfreq", _pct(g("tr_fga"), fga), fga, wins)
        if g("tr_fga"):
            _put_all(p, "trefg", _pct(g("tr_fgm") + 0.5 * g("tr_fg3m"), g("tr_fga")), g("tr_fga"), wins)
        stl = g("stl_int") + g("stl_strip") + g("stl_oth")
        if stl:
            _put_all(p, "stlint", _pct(g("stl_int"), stl), stl, wins)
        if g("blk_n"):
            _put_all(p, "blkret", _pct(g("blk_kept"), g("blk_n")), g("blk_n"), wins)
        if gp:
            _put_all(p, "ftrbl", _pct(g("g_5pf"), gp), gp, wins)
            _put_all(p, "tech", g("tech"), gp, wins, 0)
            if g("close_g"):
                _put_all(p, "closep", _pct(g("closed_close"), g("close_g")), g("close_g"), wins)
        if g("st_n"):
            _put_all(p, "stint", g("st_sec") / g("st_n") / 60.0, gp, wins)
        if g("sec"):
            _put_all(p, "q4sh", _pct(g("q4_sec"), g("sec")), gp, wins)
        if c.get("wp_games"):
            _put_all(p, "wpa", g("wpa"), gp, wins, 2)
        tov = g("tov_n")
        if tov:
            kinds = ("badpass", "lostball", "travel", "offfoul", "threesec", "shotclock", "oob", "handle", "other")
            p["tm"] = {"n": int(tov), "live": round(_pct(g("tov_live"), tov), 1),
                       "mix": {k: round(_pct(g("tov_" + k), tov), 1) for k in kinds if g("tov_" + k)}}
        if live and g("cl_sec"):
            fga_, fta_, pts_ = g("cl_fga"), g("cl_fta"), g("cl_pts")
            tsa = 2 * (fga_ + 0.44 * fta_)
            p["cl"] = {"gp": int(g("cl_gp")), "min": round(g("cl_sec") / 60.0, 1), "pts": int(pts_),
                       "fgm": int(g("cl_fgm")), "fga": int(fga_), "fg3m": int(g("cl_fg3m")), "fg3a": int(g("cl_fg3a")),
                       "ftm": int(g("cl_ftm")), "fta": int(fta_), "ast": int(g("cl_ast")), "tov": int(g("cl_tov")),
                       "pm": int(g("cl_pm")), "ts": round(100 * pts_ / tsa, 1) if tsa else None,
                       "usg": None, "net": None, "src": "espn"}
        n += 1
    return n


