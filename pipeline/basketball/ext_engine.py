def live_shots(season):
    """Shot counts for the season in progress from every team's shot chart (ESPN-built in the
    cloud, the same request shape the history uses)."""
    import ext_shots as XS
    agg = {}
    for tid in F.team_ids():
        XS.reduce_rows(F.shots_team(tid, season), agg)
    return agg


def apply_live(season, players, log=print):
    """The season in progress (refresh_current.py)."""
    if LANE != "cloud":
        return apply_all(season, players, live=True, log=log, families=("nba",))
    shots = pbp = br = None
    try:
        shots = live_shots(season)
    except Exception as e:  # noqa
        log(f"  ext shot counts: failed ({repr(e)[:80]})")
    try:
        pbp = PBP_SOURCE(season) if PBP_SOURCE else None
    except Exception as e:  # noqa
        log(f"  ext play-by-play: failed ({repr(e)[:80]})")
    try:
        import br_ext
        br = br_ext.rows(season, players, live=True)
    except Exception as e:  # noqa
        log(f"  ext Basketball Reference: failed ({repr(e)[:80]})")
    return apply_all(season, players, live=True, shots_agg=shots, pbp_counts=pbp, br_rows=br, log=log)

def apply_all(season, players, live=False, shots_agg=None, pbp_counts=None, br_rows=None, log=print,
              families=("nba", "shots", "pbp", "br", "logs")):
    out = {}
    for fam, name, fn in (("nba", "NBA tables", lambda: nba_pass(season, players, live, log=lambda *_: None)),
                          ("shots", "shot counts", lambda: shots_pass(season, players, shots_agg, live)),
                          ("pbp", "play-by-play", lambda: pbp_pass(season, players, pbp_counts, live)),
                          ("br", "Basketball Reference", lambda: br_pass(season, players, br_rows, live)),
                          ("logs", "game logs", lambda: logs_pass(season, players, live))):
        if fam not in families:
            continue
        try:
            r = fn()
            out[name] = len(r) if isinstance(r, dict) else r
        except Exception as e:  # noqa
            out[name] = f"failed ({repr(e)[:80]})"
    log(f"  ext stats: {out}")
    return out
