"""
ext_engine.py — computes the October 2026 additions (ext_config.EXT_METRICS and EXT_PANELS) for
one season's players.

    apply_all(season, players, live=..., games=..., log=print)

`players` is the season's list of player dicts as the engine builds them (p["id"], p["m"]...).
Each pass writes ext metrics into p["m"][key][window] = {"v", "n"} exactly like every other
card stat, and panels into p[panel] (p["sm"], p["dpt"], ...). Every pass is optional: a table
that is missing (not tracked that season, not reachable from the cloud) costs that family, never
the season.

Where the numbers come from (one pass per family):
  nba_pass     the NBA's tables via ext_fetch (tracking, hustle, Synergy, matchups, AWS, misc /
               usage / scoring splits, clutch, on/off, combine). On the Mac and in the history
               build these are stats.nba.com; in the cloud the shim answers from the Mac's
               upload or the public mirror, and leaves the family out if neither has it.
  shots_pass   shot zones and the shot menu from every field-goal attempt (ext_shots counts).
  pbp_pass     ESPN play-by-play counts (ext_pbp): live-ball turnovers, transition, stints,
               closing, clutch (season in progress), win probability added...
  br_pass      Basketball Reference's play-by-play table: fouls by kind, and-ones, bad-pass and
               lost-ball turnovers, points generated by assists, blocked shots, starts,
               position estimate. Reachable from the cloud, updated daily, back to 1996-97.
  logs_pass    game logs: minutes and Game Score volatility, boom / bust, floor / ceiling, and
               the home / away / win / loss / rest splits.

Per-75 stats divide by the possessions he was on the floor for in the same window
(LeagueDashPlayerStats Advanced POSS), the same denominator as every /75 bar on the card.
"""
import math
import statistics
from collections import defaultdict

import savant_config as C
import savant_engine as E
import ext_fetch as F
import ext_config as XC
import nba_extra_endpoints as NX

FAM = {m["key"]: m["fam"] for m in XC.EXT_METRICS}
WIN = {m["key"]: m["win"] for m in XC.EXT_METRICS}

# Set by cloud_refresh.py. On the Mac (LANE "mac") only the NBA's tables are requested, because
# that run exists to upload them; the cloud (LANE "cloud") builds every family.
LANE = "mac"
PBP_SOURCE = None        # cloud: callable(season) -> {nba id: ext_pbp counters} from ESPN's games


def _f(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(v) or math.isinf(v) else v


def _r(v, nd):
    return None if v is None else round(v, nd)


def _put(p, key, win, v, n, nd=1):
    # A season-only stat (ext_config win=False) is written for the full season alone, so a
    # Last-10 view hides it rather than showing the season's number under a Last-10 label.
    if v is None or (win != "season" and not WIN.get(key, True)):
        return
    p["m"].setdefault(key, {})[win] = {"v": _r(v, nd), "n": None if n is None else int(round(n))}


def _put_all(p, key, v, n, wins, nd=1):
    for w in wins:
        _put(p, key, w, v, n, nd)


def _per75(cnt, poss):
    return None if cnt is None or not poss else cnt / poss * 75


def _pct(a, b):
    return None if a is None or not b else 100.0 * a / b


def _row(df, pid):
    try:
        if pid in df.index:
            r = df.loc[pid]
            if hasattr(r, "iloc") and getattr(r, "ndim", 1) > 1:   # duplicate index rows (traded)
                r = r.iloc[0]
            return r
    except Exception:  # noqa
        pass
    return None


def _g(r, col):
    if r is None:
        return None
    try:
        return _f(r.get(col))
    except Exception:  # noqa
        return None


def _windows(live):
    return list(C.WINDOWS.items()) if live else [("season", None)]


def _poss_map(ln, season):
    try:
        adv = E.load_adv(ln, season)
        return {int(pid): _f(r.get("poss")) or 0.0 for pid, r in adv.iterrows()}
    except Exception:  # noqa
        return {}


def _box_map(ln, season):
    try:
        return E.load_box(ln, season)
    except Exception:  # noqa
        return None


# ===================================================================== NBA tables
def nba_pass(season, players, live=False, log=print):
    by_id = {p["id"]: p for p in players}
    done = defaultdict(int)
    season_poss = _poss_map(None, season)
    all_wins = list(C.WINDOWS.keys()) if live else ["season"]

    for win, ln in _windows(live):
        poss = _poss_map(ln, season)
        box = _box_map(ln, season)

        def put(pid, key, v, n, nd=1):
            p = by_id.get(int(pid))
            if p is not None and v is not None:
                _put(p, key, win, v, n, nd)
                done[key] += 1

        # ---- possessions / touches
        t = F.track("Possessions", ln, season)
        for pid, r in t.iterrows():
            ps = poss.get(int(pid))
            tch = _g(r, "TOUCHES")
            put(pid, "tch75", _per75(tch, ps), ps)
            put(pid, "fct75", _per75(_g(r, "FRONT_CT_TOUCHES"), ps), ps)
            put(pid, "top75", _per75(_g(r, "TIME_OF_POSS"), ps), ps, 2)
            if tch:
                put(pid, "spt", _g(r, "AVG_SEC_PER_TOUCH"), tch, 2)
                put(pid, "dpt", _g(r, "AVG_DRIB_PER_TOUCH"), tch, 2)
                put(pid, "ppt", _g(r, "PTS_PER_TOUCH"), tch, 2)
            put(pid, "elb75", _per75(_g(r, "ELBOW_TOUCHES"), ps), ps)
            put(pid, "post75", _per75(_g(r, "POST_TOUCHES"), ps), ps)
            put(pid, "pnt75", _per75(_g(r, "PAINT_TOUCHES"), ps), ps)
        for measure, key, prefix in (("PostTouch", "postpts", "POST_TOUCH"), ("ElbowTouch", "elbpts", "ELBOW_TOUCH")):
            t = F.track(measure, ln, season)
            for pid, r in t.iterrows():
                n = _g(r, prefix + "ES")
                if n:
                    put(pid, key, (_g(r, prefix + "_PTS") or 0) / n, n, 2)

        # ---- pull-up / catch-and-shoot
        pu = F.track("PullUpShot", ln, season)
        cs = F.track("CatchShoot", ln, season)
        for pid, r in pu.iterrows():
            ps = poss.get(int(pid))
            fga, f3a = _g(r, "PULL_UP_FGA"), _g(r, "PULL_UP_FG3A")
            put(pid, "pu_fga", _per75(fga, ps), ps)
            put(pid, "pu_3pa", _per75(f3a, ps), ps)
            if fga:
                put(pid, "pu_efg", 100 * (_g(r, "PULL_UP_EFG_PCT") or 0), fga)
            if f3a:
                put(pid, "pu_3p", 100 * (_g(r, "PULL_UP_FG3_PCT") or 0), f3a)
        for pid, r in cs.iterrows():
            ps = poss.get(int(pid))
            fga, f3a = _g(r, "CATCH_SHOOT_FGA"), _g(r, "CATCH_SHOOT_FG3A")
            put(pid, "cs_3pa", _per75(f3a, ps), ps)
            if f3a:
                put(pid, "cs_3p", 100 * (_g(r, "CATCH_SHOOT_FG3_PCT") or 0), f3a)
            if fga:
                put(pid, "cs_efg", 100 * (_g(r, "CATCH_SHOOT_EFG_PCT") or 0), fga)
            pr = _row(pu, pid)
            pfga = _g(pr, "PULL_UP_FGA") or 0.0
            if fga is not None and (pfga + fga) > 0:
                put(pid, "pushare", 100 * pfga / (pfga + fga), pfga + fga)

        # ---- drives
        d = F.track("Drives", ln, season)
        for pid, r in d.iterrows():
            dv = _g(r, "DRIVES")
            if not dv:
                continue
            put(pid, "drvpts", (_g(r, "DRIVE_PTS") or 0) / dv, dv, 2)
            fga = _g(r, "DRIVE_FGA")
            if fga:
                put(pid, "drvfg", 100 * (_g(r, "DRIVE_FGM") or 0) / fga, fga)
            put(pid, "drvft", _pct(_g(r, "DRIVE_FTA"), dv), dv)
            put(pid, "drvpass", _pct(_g(r, "DRIVE_PASSES"), dv), dv)
            put(pid, "drvast", _pct(_g(r, "DRIVE_AST"), dv), dv)
            put(pid, "drvtov", _pct(_g(r, "DRIVE_TOV"), dv), dv)

        # ---- passing
        pa = F.track("Passing", ln, season)
        for pid, r in pa.iterrows():
            ps = poss.get(int(pid))
            passes = _g(r, "PASSES_MADE")
            pot, ast = _g(r, "POTENTIAL_AST"), _g(r, "AST")
            # same guard as the potential-assists bar: the NBA occasionally publishes impossible rows
            bad = (passes and pot and pot > passes) or (ast and ast >= 5 and pot and pot > 5 * ast)
            put(pid, "pass75", _per75(passes, ps), ps)
            put(pid, "secast75", _per75(_g(r, "SECONDARY_AST"), ps), ps, 2)
            put(pid, "ftast75", _per75(_g(r, "FT_AST"), ps), ps, 2)
            apc = _g(r, "AST_PTS_CREATED")
            put(pid, "astpts75", _per75(apc, ps), ps)
            if passes:
                put(pid, "astpass", 100 * (_g(r, "AST_TO_PASS_PCT_ADJ") or 0), passes)
            if pot and not bad:
                put(pid, "astconv", 100 * (ast or 0) / pot, pot)
            br = _row(box, int(pid)) if box is not None else None
            pts = _g(br, "pts")
            if pts is not None and apc is not None:
                put(pid, "ptsc75", _per75(pts + apc, ps), ps)

        # ---- speed and distance
        sd = F.track("SpeedDistance", ln, season)
        for pid, r in sd.iterrows():
            mins = _g(r, "MIN")
            if not mins:
                continue
            put(pid, "mi48", (_g(r, "DIST_MILES") or 0) / mins * 48, mins, 2)
            put(pid, "spdo", _g(r, "AVG_SPEED_OFF"), mins, 2)
            put(pid, "spdd", _g(r, "AVG_SPEED_DEF"), mins, 2)

        # ---- rebounding
        rb = F.track("Rebounding", ln, season)
        for pid, r in rb.iterrows():
            ps = poss.get(int(pid))
            reb, ch = _g(r, "REB"), _g(r, "REB_CHANCES")
            if reb:
                put(pid, "crebp", 100 * (_g(r, "REB_CONTEST_PCT") or 0), reb)
                put(pid, "rebdist", _g(r, "AVG_REB_DIST"), reb)
            put(pid, "creb75", _per75(_g(r, "REB_CONTEST"), ps), ps)
            put(pid, "rebch75", _per75(ch, ps), ps)
            if ch:
                put(pid, "rebconv", 100 * (_g(r, "REB_CHANCE_PCT") or 0), ch)
                put(pid, "rebadj", 100 * (_g(r, "REB_CHANCE_PCT_ADJ") or 0), ch)
            put(pid, "rebdef75", _per75(_g(r, "REB_CHANCE_DEFER"), ps), ps, 2)

        # ---- rim contests
        df_ = F.track("Defense", ln, season)
        for pid, r in df_.iterrows():
            ps = poss.get(int(pid))
            put(pid, "rimc75", _per75(_g(r, "DEF_RIM_FGA"), ps), ps)

        # ---- closest-defender threes
        bands = {k: F.ptshot(ln, season, close_def_dist_range_nullable=v) for k, v in F.DEF_BANDS.items()}
        for key, band in (("wo3p", "wide"), ("op3p", "open")):
            for pid, r in bands[band].iterrows():
                a = _g(r, "FG3A")
                if a:
                    put(pid, key, 100 * (_g(r, "FG3M") or 0) / a, a)
        tight = defaultdict(lambda: [0.0, 0.0])
        for band in ("vtight", "tight"):
            for pid, r in bands[band].iterrows():
                tight[int(pid)][0] += _g(r, "FG3M") or 0
                tight[int(pid)][1] += _g(r, "FG3A") or 0
        for pid, (m_, a) in tight.items():
            if a:
                put(pid, "tg3p", 100 * m_ / a, a)

        # ---- defended shots by category
        for cat, key, a_col, pm_col in (("Overall", "dfgall", "D_FGA", "PCT_PLUSMINUS"),
                                        ("3 Pointers", "dfg3", "FG3A", "PLUSMINUS"),
                                        ("2 Pointers", "dfg2", "FG2A", "PLUSMINUS"),
                                        ("Less Than 10Ft", "dfg10", "FGA_LT_10", "PLUSMINUS"),
                                        ("Greater Than 15Ft", "dfg15", "FGA_GT_15", "PLUSMINUS")):
            for pid, r in F.ptdefend(cat, ln, season).iterrows():
                a = _g(r, a_col)
                if a:
                    put(pid, key, 100 * (_g(r, pm_col) or 0), a)

        # ---- misc / usage / scoring / box
        mi = F.measure("Misc", ln, season)
        for pid, r in mi.iterrows():
            ps = poss.get(int(pid))
            put(pid, "fbp75", _per75(_g(r, "PTS_FB"), ps), ps)
            put(pid, "ptov75", _per75(_g(r, "PTS_OFF_TOV"), ps), ps)
            put(pid, "scp75", _per75(_g(r, "PTS_2ND_CHANCE"), ps), ps)
        us = F.measure("Usage", ln, season)
        for pid, r in us.iterrows():
            ps = poss.get(int(pid))
            for key, col in (("tmpts", "PCT_PTS"), ("tmast", "PCT_AST"), ("tmreb", "PCT_REB"), ("tmblk", "PCT_BLK")):
                v = _g(r, col)
                if v is not None:
                    put(pid, key, 100 * v, ps)
        for pid, r in mi.iterrows():
            # fouls drawn: the NBA's own count (Misc). The cloud's ESPN-built box score can't
            # name who drew a non-shooting foul, so this one comes from the NBA's table only.
            ps = poss.get(int(pid))
            put(pid, "pfd75", _per75(_g(r, "PFD"), ps), ps)
        if box is not None:
            for pid, r in box.iterrows():
                ps = poss.get(int(pid))
                put(pid, "pf75", _per75(_g(r, "pf"), ps), ps)
        sc = F.measure("Scoring", ln, season)
        if len(sc) and box is not None:
            for pid, r in sc.iterrows():
                pts = _g(_row(box, int(pid)), "pts")
                if not pts:
                    continue
                for key, col in (("pfb", "PCT_PTS_FB"), ("pft", "PCT_PTS_FT"), ("pmr", "PCT_PTS_2PT_MR")):
                    v = _g(r, col)
                    if v is not None:
                        put(pid, key, 100 * v, pts)

    # ================= season-only NBA tables (spread over every window like grav / syn)
    def put_s(pid, key, v, n, nd=1):
        p = by_id.get(int(pid))
        if p is not None and v is not None:
            _put_all(p, key, v, n, all_wins, nd)
            done[key] += 1

    # late clock
    late = F.ptshot(None, season, shot_clock_range_nullable="4-0 Very Late")
    box_s = _box_map(None, season)
    for pid, r in late.iterrows():
        fga = _g(r, "FGA")
        tot = _g(_row(box_s, int(pid)), "fga") if box_s is not None else None
        if tot:
            put_s(pid, "ltc_freq", 100 * (fga or 0) / tot, tot)
        if fga:
            put_s(pid, "ltc_efg", 100 * (_g(r, "EFG_PCT") or 0), fga)

    # hustle
    hu = F.hustle(season)
    if len(hu):
        has_box = (hu["BOX_OUTS"].astype(float).sum() > 0) if "BOX_OUTS" in hu.columns else False
        for pid, r in hu.iterrows():
            ps = season_poss.get(int(pid))
            put_s(pid, "scrast75", _per75(_g(r, "SCREEN_ASSISTS"), ps), ps)
            put_s(pid, "scrpts75", _per75(_g(r, "SCREEN_AST_PTS"), ps), ps)
            put_s(pid, "cont75", _per75(_g(r, "CONTESTED_SHOTS"), ps), ps)
            put_s(pid, "cont3_75", _per75(_g(r, "CONTESTED_SHOTS_3PT"), ps), ps)
            put_s(pid, "chg75", _per75(_g(r, "CHARGES_DRAWN"), ps), ps, 2)
            put_s(pid, "lbr75", _per75(_g(r, "LOOSE_BALLS_RECOVERED"), ps), ps, 2)
            if has_box:
                bo = _g(r, "BOX_OUTS")
                put_s(pid, "box75", _per75(bo, ps), ps)
                if bo:
                    put_s(pid, "boxtm", 100 * (_g(r, "PCT_BOX_OUTS_TEAM_REB") or 0), bo)

    # gravity (all five), shot quality, leverage
    gv = F.aws(NX.GravityLeadersRaw, season)
    for _, r in gv.iterrows():
        pid = int(r["PLAYERID"])
        put_s(pid, "gravall", _g(r, "AVGGRAVITYSCORE"), _g(r, "FRAMES"))
        put_s(pid, "gravonp", _g(r, "AVGONBALLPERIMETERGRAVITYSCORE"), _g(r, "ONBALLPERIMETERFRAMES"))
        put_s(pid, "gravoni", _g(r, "AVGONBALLINTERIORGRAVITYSCORE"), _g(r, "ONBALLINTERIORFRAMES"))
        put_s(pid, "gravoffi", _g(r, "AVGOFFBALLINTERIORGRAVITYSCORE"), _g(r, "OFFBALLINTERIORFRAMES"))
    sq = F.aws(NX.ShotQualityLeaders, season)
    for _, r in sq.iterrows():
        pid = int(r["PLAYERID"])
        fga = _g(r, "FGA")
        f3a = _g(r, "FG3A")
        put_s(pid, "nxfg", _scale_pct(_g(r, "AVGSHOTQUALITY")), fga)
        put_s(pid, "nfgx", _scale_pct(_g(r, "FGPCTABOVEEXPECTED")), fga)
        put_s(pid, "n3px", _scale_pct(_g(r, "FG3PCTABOVEEXPECTED")), f3a)
        put_s(pid, "ndd", _g(r, "AVGDEFENDERBALLDISTANCE"), fga)
        put_s(pid, "ndp", _g(r, "AVGDEFENDERPRESSURESCORE"), fga, 2)
    lv = F.aws(NX.LeverageLeaders, season)
    for _, r in lv.iterrows():
        pid = int(r["PLAYERID"])
        gp = _g(r, "GAMESPLAYED")
        for key, col in (("lev", "FULL"), ("levo", "OFFENSE"), ("levd", "DEFENSE"), ("levob", "ONBALLDEF"),
                         ("levsh", "SHOOTING"), ("levcr", "CREATION"), ("levrb", "REBOUNDS"), ("levto", "TURNOVERS")):
            put_s(pid, key, _g(r, col), gp, 3)

    # matchups: help, turnovers forced, shooting fouls
    mt = F.matchups(season)
    if len(mt):
        agg = defaultdict(lambda: defaultdict(float))
        lg_hm = lg_ha = 0.0
        for _, r in mt.iterrows():
            a = agg[int(r["DEF_PLAYER_ID"])]
            for col in ("PARTIAL_POSS", "MATCHUP_TOV", "SFL", "HELP_BLK", "HELP_FGM", "HELP_FGA"):
                a[col] += _g(r, col) or 0.0
            lg_hm += _g(r, "HELP_FGM") or 0.0
            lg_ha += _g(r, "HELP_FGA") or 0.0
        lg = lg_hm / lg_ha if lg_ha else None
        for pid, a in agg.items():
            ps = season_poss.get(pid)
            pp = a["PARTIAL_POSS"]
            if lg_ha:                      # 2016-17's table has the columns but no help data
                put_s(pid, "helpblk75", _per75(a["HELP_BLK"], ps), ps, 2)
                if a["HELP_FGA"] and lg is not None:
                    put_s(pid, "helpfg", 100 * (a["HELP_FGM"] / a["HELP_FGA"] - lg), a["HELP_FGA"])
            if pp:
                put_s(pid, "mtov", 100 * a["MATCHUP_TOV"] / pp, pp, 2)
                put_s(pid, "msfl", 100 * a["SFL"] / pp, pp, 2)
    ru = F.rollup(season)
    if len(ru):
        shares = defaultdict(dict)
        tot = {}
        for _, r in ru.iterrows():
            pid, pos = int(r["DEF_PLAYER_ID"]), str(r["POSITION"])
            if pos == "TOTAL":
                tot[pid] = _g(r, "PARTIAL_POSS") or 0.0
            else:
                shares[pid][pos] = _g(r, "PERCENT_OF_TIME") or 0.0
        for pid, sh in shares.items():
            s = sum(sh.values())
            if s <= 0:
                continue
            ent = -sum((v / s) * math.log(v / s) for v in sh.values() if v > 0)
            put_s(pid, "vers", 100 * ent / math.log(3), tot.get(pid), 0)

    # defensive box scores: switches
    gids = F.defbox_game_ids(season) if F.has("match", season) else []
    sw = defaultdict(lambda: [0.0, 0.0])
    for gid in gids:
        db = F.defbox(gid)
        if not len(db):
            continue
        for _, r in db.iterrows():
            pp = _g(r, "partialPossessions")
            if pp:
                a = sw[int(r["personId"])]
                a[0] += _g(r, "switchesOn") or 0.0
                a[1] += pp
    for pid, (s_, pp) in sw.items():
        if pp:
            put_s(pid, "swr", 100 * s_ / pp, pp)

    # on/off offense and defense (summary, Advanced): minutes-weighted across teams
    oo = defaultdict(lambda: [0.0, 0.0, 0.0])
    f4 = defaultdict(lambda: {"on": defaultdict(float), "off": defaultdict(float), "m_on": 0.0, "m_off": 0.0})
    for tid in F.team_ids():
        on, off = F.onoff_summary(tid, season)
        if len(on) and len(off):
            on_, off_ = on.set_index("VS_PLAYER_ID"), off.set_index("VS_PLAYER_ID")
            for pid in on_.index:
                if pid not in off_.index:
                    continue
                ro, rf = _row(on_, pid), _row(off_, pid)
                mins = _g(ro, "MIN") or 0.0
                if mins <= 0:
                    continue
                a = oo[int(pid)]
                a[0] += ((_g(ro, "OFF_RATING") or 0) - (_g(rf, "OFF_RATING") or 0)) * mins
                a[1] += ((_g(ro, "DEF_RATING") or 0) - (_g(rf, "DEF_RATING") or 0)) * mins
                a[2] += mins
        on, off = F.onoff_details(tid, season)
        if len(on) and len(off):
            on_, off_ = on.set_index("VS_PLAYER_ID"), off.set_index("VS_PLAYER_ID")
            for pid in on_.index:
                if pid not in off_.index:
                    continue
                ro, rf = _row(on_, pid), _row(off_, pid)
                mo, mf = _g(ro, "MIN") or 0.0, _g(rf, "MIN") or 0.0
                if mo <= 0:
                    continue
                d = f4[int(pid)]
                for col in ("EFG_PCT", "FTA_RATE", "TM_TOV_PCT", "OREB_PCT", "OPP_EFG_PCT", "OPP_FTA_RATE", "OPP_TOV_PCT", "OPP_OREB_PCT"):
                    d["on"][col] += (_g(ro, col) or 0) * mo
                    d["off"][col] += (_g(rf, col) or 0) * mf
                d["m_on"] += mo
                d["m_off"] += mf
    for pid, (o, dd, mins) in oo.items():
        if mins:
            put_s(pid, "onoffo", o / mins, mins)
            put_s(pid, "onoffd", dd / mins, mins)
    for pid, d in f4.items():
        p = by_id.get(pid)
        if p is None or not d["m_on"] or not d["m_off"]:
            continue
        cols = ("EFG_PCT", "TM_TOV_PCT", "OREB_PCT", "FTA_RATE", "OPP_EFG_PCT", "OPP_TOV_PCT", "OPP_OREB_PCT", "OPP_FTA_RATE")
        p["off4"] = {"min": [round(d["m_on"]), round(d["m_off"])],
                     "on": [round(100 * d["on"][c] / d["m_on"], 1) for c in cols],
                     "off": [round(100 * d["off"][c] / d["m_off"], 1) for c in cols]}

    try:
        _panels_nba(season, by_id, live)
    except Exception as e:  # noqa
        log(f"  ext panels (NBA): failed ({repr(e)[:80]})")
    _combine(season, by_id, all_wins)
    log(f"  ext NBA tables: {sum(1 for k in done)} stats on {len({p['id'] for p in players if any(k in p['m'] for k in done)})} players")
    return done


def _scale_pct(v):
    """The AWS tables give rates as fractions (0.438) or as percents (43.8) depending on the
    column; normalise to percent points."""
    if v is None:
        return None
    return v * 100 if abs(v) <= 1.5 else v


def _panels_nba(season, by_id, live):
    # ---- shot splits (season): dribbles, touch time, shot clock, defender distance
    splits = [("drib", "dribble_range_nullable", F.DRIBBLES), ("touch", "touch_time_range_nullable", F.TOUCH),
              ("clock", "shot_clock_range_nullable", F.CLOCK)]
    out = defaultdict(dict)
    for name, param, vals in splits:
        for v in vals:
            df = F.ptshot(None, season, **{param: v})
            for pid, r in df.iterrows():
                fga = _g(r, "FGA")
                if fga:
                    out[int(pid)].setdefault(name, {})[v] = [round(100 * (_g(r, "FGA_FREQUENCY") or 0), 1),
                                                             round(100 * (_g(r, "EFG_PCT") or 0), 1), int(fga)]
    for band_key, v in F.DEF_BANDS.items():
        df = F.ptshot(None, season, close_def_dist_range_nullable=v)
        for pid, r in df.iterrows():
            fga = _g(r, "FGA")
            if fga:
                out[int(pid)].setdefault("def", {})[v] = [round(100 * (_g(r, "FGA_FREQUENCY") or 0), 1),
                                                          round(100 * (_g(r, "EFG_PCT") or 0), 1), int(fga)]
    for pid, v in out.items():
        if pid in by_id:
            by_id[pid]["ss"] = v

    # ---- touches (season)
    poss = _poss_map(None, season)
    tp = defaultdict(dict)
    for measure, kind, prefix in (("ElbowTouch", "elbow", "ELBOW_TOUCH"), ("PostTouch", "post", "POST_TOUCH"),
                                  ("PaintTouch", "paint", "PAINT_TOUCH")):
        df = F.track(measure, None, season)
        for pid, r in df.iterrows():
            n = _g(r, prefix + "ES")
            if not n:
                continue
            ps = poss.get(int(pid))
            fga = _g(r, prefix + "_FGA") or 0
            tp[int(pid)][kind] = [
                _r(_per75(n, ps), 1), round((_g(r, prefix + "_PTS") or 0) / n, 2),
                round(100 * (_g(r, prefix + "_FGM") or 0) / fga, 1) if fga else None,
                round(100 * (_g(r, prefix + "_PASSES_PCT") or 0), 1), round(100 * (_g(r, prefix + "_AST_PCT") or 0), 1),
                round(100 * (_g(r, prefix + "_TOV_PCT") or 0), 1), round(100 * (_g(r, prefix + "_FOULS_PCT") or 0), 1), int(n)]
    for pid, v in tp.items():
        if pid in by_id:
            by_id[pid]["tp"] = v

    # ---- defensive play types and the offense panel's extra columns
    dpt = defaultdict(dict)
    for pt in F.SYN_DEF:
        df = F.synergy(pt, "defensive", season)
        for _, r in df.iterrows():
            pid, poss_ = int(r["PLAYER_ID"]), _g(r, "POSS") or 0.0
            if poss_ <= 0:
                continue
            prev = dpt[pid].get(pt)
            ppp, freq = _g(r, "PPP") or 0.0, 100 * (_g(r, "POSS_PCT") or 0.0)
            pct = _g(r, "PERCENTILE")
            if prev:   # traded: combine, possession-weighted
                tp_ = prev[3] + poss_
                prev[1] = round((prev[1] * prev[3] + ppp * poss_) / tp_, 3)
                prev[0] = round((prev[0] * prev[3] + freq * poss_) / tp_, 1)
                prev[2] = None
                prev[3] = round(tp_)
            else:
                dpt[pid][pt] = [round(freq, 1), round(ppp, 3), None if pct is None else round(100 * pct), round(poss_)]
    if live:
        # the NBA's percentile is ranked inside its 10-possession pool: rank ours, as the offense panel does
        import extras_engine as XE
        pool = defaultdict(list)
        for pid, types in dpt.items():
            for t, v in types.items():
                if v[3] >= XE.SAMPLE_FLAG:
                    pool[t].append(v[1])
        for pid, types in dpt.items():
            for t, v in types.items():
                vals = pool.get(t, [])
                pc = None if (v[3] < XE.SAMPLE_FLAG or len(vals) < XE.POOL_MIN) else XE._midrank(v[1], vals)
                v[2] = None if pc is None else round(100 - pc)   # fewer points allowed = better
    for pid, v in dpt.items():
        if pid in by_id:
            by_id[pid]["dpt"] = v
    ptx = defaultdict(dict)
    for pt in F.SYN_OFF:
        df = F.synergy(pt, "offensive", season)
        for _, r in df.iterrows():
            pid, poss_ = int(r["PLAYER_ID"]), _g(r, "POSS") or 0.0
            if poss_ <= 0:
                continue
            vals = [100 * (_g(r, c) or 0.0) for c in ("TOV_POSS_PCT", "FT_POSS_PCT", "SF_POSS_PCT", "PLUSONE_POSS_PCT",
                                                      "SCORE_POSS_PCT", "EFG_PCT")]
            prev = ptx[pid].get(pt)
            if prev:
                n0 = prev[6]
                tp_ = n0 + poss_
                ptx[pid][pt] = [round((a * n0 + b * poss_) / tp_, 1) for a, b in zip(prev[:6], vals)] + [round(tp_)]
            else:
                ptx[pid][pt] = [round(v, 1) for v in vals] + [round(poss_)]
    for pid, v in ptx.items():
        if pid in by_id:
            by_id[pid]["ptx"] = v

    # ---- passing network (who he passes to / gets passes from)
    for pid in (F.network_players(season) if F.has("track", season) else []):
        p = by_id.get(pid)
        if p is None:
            continue
        made, recv = F.pass_network(pid, season)
        if not len(made):
            continue

        def rows(df, who):
            out_ = []
            for _, r in df.iterrows():
                passes = _g(r, "PASS") or 0.0
                if passes < 50:
                    continue
                fga = _g(r, "FGA") or 0.0
                out_.append([int(r["PASS_TEAMMATE_PLAYER_ID"]), str(r.get(who) or ""), int(passes),
                             int(_g(r, "AST") or 0), int(_g(r, "FGM") or 0), int(fga), int(_g(r, "FG3M") or 0), int(_g(r, "FG3A") or 0)])
            out_.sort(key=lambda x: -x[2])
            return out_[:8]
        p["pn"] = {"made": rows(made, "PASS_TO"), "recv": rows(recv, "PASS_FROM") if len(recv) else []}

    # ---- clutch (NBA's own; the season in progress gets ESPN's in pbp_pass instead)
    if not live:
        cb, ca = F.clutch("Base", season), F.clutch("Advanced", season)
        for pid, r in cb.iterrows():
            p = by_id.get(int(pid))
            if p is None:
                continue
            ra = _row(ca, pid)
            fga, fta, pts = _g(r, "FGA") or 0, _g(r, "FTA") or 0, _g(r, "PTS") or 0
            tsa = 2 * (fga + 0.44 * fta)
            p["cl"] = {"gp": int(_g(r, "GP") or 0), "min": round(_g(r, "MIN") or 0, 1), "pts": int(pts),
                       "fgm": int(_g(r, "FGM") or 0), "fga": int(fga), "fg3m": int(_g(r, "FG3M") or 0),
                       "fg3a": int(_g(r, "FG3A") or 0), "ftm": int(_g(r, "FTM") or 0), "fta": int(fta),
                       "ast": int(_g(r, "AST") or 0), "tov": int(_g(r, "TOV") or 0), "pm": int(_g(r, "PLUS_MINUS") or 0),
                       "ts": round(100 * pts / tsa, 1) if tsa else None,
                       "usg": None if ra is None else _r(100 * (_g(ra, "USG_PCT") or 0), 1),
                       "net": None if ra is None else _r(_g(ra, "NET_RATING"), 1), "src": "nba"}

    # ---- starters / bench (NBA's split; the season in progress gets ESPN's)
    if not live:
        for which, tag in (("Starters", "start"), ("Bench", "bench")):
            df = F.starters(season, which)
            for pid, r in df.iterrows():
                p = by_id.get(int(pid))
                gp = _g(r, "GP")
                if p is None or not gp:
                    continue
                fga, fta, pts = _g(r, "FGA") or 0, _g(r, "FTA") or 0, _g(r, "PTS") or 0
                tsa = 2 * (fga + 0.44 * fta)
                p.setdefault("sp", {})[tag] = [int(gp), round((_g(r, "MIN") or 0) / gp, 1), round(pts / gp, 1),
                                               round((_g(r, "REB") or 0) / gp, 1), round((_g(r, "AST") or 0) / gp, 1),
                                               round(100 * pts / tsa, 1) if tsa else None,
                                               round((_g(r, "PLUS_MINUS") or 0) / gp, 1)]

    # ---- handle score and dunk score
    hs = F.aws(NX.HandleScore, season)
    if len(hs):
        byp = defaultdict(list)
        for _, r in hs.iterrows():
            byp[int(r["PLAYER_ID"])].append(r)
        for pid, rows_ in byp.items():
            p = by_id.get(pid)
            if p is None:
                continue
            sc = [(_g(r, "HANDLE_SCORE") or 0.0) for r in rows_]
            top = sorted(rows_, key=lambda r: -(_g(r, "HANDLE_SCORE") or 0))[:3]
            p["hs"] = {"n": len(sc), "avg": round(statistics.mean(sc), 1), "max": round(max(sc), 1),
                       "top": [[round(_g(r, "HANDLE_SCORE") or 0, 1), int(_g(r, "DRIBBLES") or 0),
                                int(_g(r, "THROUGH_LEGS_COUNT") or 0), int(_g(r, "BEHIND_BACK_COUNT") or 0),
                                int(_g(r, "SPIN_COUNT") or 0), int(_g(r, "HAND_SWITCH_COUNT") or 0),
                                _r(_g(r, "MAX_SPEED"), 1), _r(_g(r, "TOTAL_DISTANCE"), 1),
                                str(r.get("DEFENDER_ON_GROUND") or ""), str(r.get("GAME_DATE") or ""),
                                f"{r.get('AWAY_TEAM_ABBREVIATION', '')} @ {r.get('HOME_TEAM_ABBREVIATION', '')}"] for r in top]}
    dk = F.aws(NX.DunkScoreLeadersRaw, season)
    if len(dk):
        byp = defaultdict(list)
        pcol = "playerId" if "playerId" in dk.columns else "PLAYER_ID"
        for _, r in dk.iterrows():
            byp[int(r[pcol])].append(r)
        for pid, rows_ in byp.items():
            p = by_id.get(pid)
            if p is None:
                continue
            sc = [(_g(r, "dunkScore") or 0.0) for r in rows_]
            vert = [v for v in (_g(r, "playerVertical") for r in rows_) if v is not None]
            hang = [v for v in (_g(r, "hangTime") for r in rows_) if v is not None]
            top = sorted(rows_, key=lambda r: -(_g(r, "dunkScore") or 0))[:3]
            p["dk"] = {"n": len(sc), "avg": round(statistics.mean(sc), 1), "max": round(max(sc), 1),
                       "vert": _r(max(vert), 1) if vert else None, "hang": _r(max(hang), 2) if hang else None,
                       "top": [[round(_g(r, "dunkScore") or 0, 1), _r(_g(r, "jumpSubscore"), 1), _r(_g(r, "powerSubscore"), 1),
                                _r(_g(r, "styleSubscore"), 1), _r(_g(r, "defensiveContestSubscore"), 1),
                                _r(_g(r, "playerVertical"), 1), _r(_g(r, "hangTime"), 2),
                                str(r.get("gameDate") or "").split(" ")[0], str(r.get("matchup") or "")] for r in top]}


def _combine(season, by_id, wins):
    """The combine numbers the card didn't show yet (standing vertical, sprint, bench, hands,
    body fat). Same draft-class loop as savant_engine._attach_combine, so the cache is shared."""
    from nba_api.stats.endpoints import draftcombinestats as S
    for yr in range(2000, int(season[:4]) + 1):
        sy = f"{yr}-{str(yr + 1)[2:]}"
        try:
            st = E.call(S.DraftCombineStats, dict(season_all_time=sy, league_id="00")).set_index("PLAYER_ID")
        except Exception:  # noqa
            continue
        for pid, p in by_id.items():
            r = _row(st, pid)
            if r is None:
                continue
            for key, col, nd in (("svert", "STANDING_VERTICAL_LEAP", 1), ("sprint", "THREE_QUARTER_SPRINT", 2),
                                 ("bench", "BENCH_PRESS", 0), ("handl", "HAND_LENGTH", 2), ("handw", "HAND_WIDTH", 2),
                                 ("bfat", "BODY_FAT_PCT", 1)):
                v = _g(r, col)
                if v:   # 0 / blank = not measured
                    _put_all(p, key, v, None, wins, nd)


