"""
br_ext.py — Basketball Reference's per-season play-by-play table, keyed by NBA player id.

    python3 br_ext.py history <out_dir> 1997 2026     # end years; writes <out_dir>/<season>.json
    rows(season, live=False) -> {nba id: {data-stat: text}}

The play-by-play table (NBA_<year>_play-by-play.html, id "pbp_stats") is the long-history,
cloud-reachable source for: shooting / offensive fouls committed and drawn, and-ones, bad-pass
and lost-ball turnovers, points generated by assists, own shots blocked, games started, and the
position estimate. 1996-97 on; Basketball Reference updates it every morning in season, so the
cloud refresh reads the season in progress fresh each run.

Players traded mid-season appear once per team plus a combined row ("2TM", "3TM", or "TOT" in
older pages); the combined row is the one kept. Names are matched to NBA ids against that
season's players in the archive (unique normalised name, preferring the same team).
"""
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import br_fetch as B  # noqa: E402

KIND = "play-by-play"
TABLE = "pbp_stats"
KEEP = ("games", "games_started", "mp", "pct_1", "pct_2", "pct_3", "pct_4", "pct_5", "plus_minus_on",
        "plus_minus_net", "tov_bad_pass", "tov_lost_ball", "fouls_shooting", "fouls_offensive",
        "drawn_shooting", "drawn_offensive", "astd_pts", "and1s", "own_shots_blk")
TEAM_FIX = {"PHO": "PHX", "BRK": "BKN", "CHO": "CHA", "NOH": "NOP", "NOK": "NOP", "NJN": "BKN", "SEA": "OKC",
            "VAN": "MEM", "CHH": "CHA", "WSB": "WAS", "GOS": "GSW", "UTH": "UTA"}


from namematch import Matcher, norm  # noqa: E402,F401


def season_of(end_year):
    return f"{end_year - 1}-{str(end_year)[2:]}"


def fetch(end_year, fresh=False):
    """HTML of the table page; `fresh` skips the disk cache (the season in progress)."""
    import requests
    B.TABLE_ID.setdefault(KIND, TABLE)
    cp = B.cache_path(end_year, KIND)
    if not fresh and os.path.exists(cp):
        return open(cp, encoding="utf-8").read()
    url = B.BASE.format(year=end_year, kind=KIND)
    last = None
    for attempt in range(B.RETRIES):
        try:
            r = requests.get(url, headers={"User-Agent": B.UA}, timeout=30)
            r.encoding = "utf-8"
            if r.status_code == 200 and f'id="{TABLE}"' in r.text:
                os.makedirs(B.BR_CACHE, exist_ok=True)
                open(cp, "w", encoding="utf-8").write(r.text)
                time.sleep(B.REQUEST_DELAY)
                return r.text
            last = f"status {r.status_code}"
        except Exception as e:  # noqa
            last = repr(e)[:120]
        time.sleep(B.REQUEST_DELAY * (attempt + 2))
    raise RuntimeError(f"Basketball Reference {season_of(end_year)} {KIND}: {last}")


def parse(html):
    p = B._TableRows(TABLE)
    p.feed(html)
    out = {}
    for r in p.rows:
        bid = r.get("br_id")
        team = r.get("team_name_abbr") or r.get("team_id") or ""
        combined = bool(re.match(r"^(\dTM|TOT)$", team))
        if bid in out and not combined:
            continue           # keep the combined row of a traded player
        out[bid] = dict({k: r.get(k) for k in KEEP}, name=r.get("name_display") or r.get("player"),
                        team=TEAM_FIX.get(team, team), combined=combined)
    return out


def to_nba(br_rows, players):
    """{br id: row} -> {nba id: row}, matched against that season's archive players."""
    m = Matcher(players)
    out, miss = {}, []
    for bid, r in br_rows.items():
        nid = m.find(r["name"], "" if r.get("combined") else r["team"])
        if nid is not None and nid not in out:
            out[nid] = r
        else:
            miss.append(r["name"])
    return out, miss


def rows(season, players, live=False):
    end_year = int(season[:4]) + 1
    return to_nba(parse(fetch(end_year, fresh=live)), players)[0]


def history(out_dir, first, last):
    os.makedirs(out_dir, exist_ok=True)
    data = json.load(open(os.path.join(HERE, "..", "..", "public", "savant-data.json")))
    for ey in range(int(first), int(last) + 1):
        s = season_of(ey)
        players = data["data"].get(s, {}).get("players", [])
        if not players:
            print(f"{s}: no archive players")
            continue
        try:
            got, miss = to_nba(parse(fetch(ey)), players)
        except Exception as e:  # noqa
            print(f"{s}: failed {e}")
            continue
        json.dump({str(k): {kk: vv for kk, vv in v.items() if kk not in ("name",)} for k, v in got.items()},
                  open(os.path.join(out_dir, f"{s}.json"), "w"), separators=(",", ":"))
        print(f"{s}: {len(got)} matched, {len(miss)} unmatched {miss[:5]}", flush=True)


if __name__ == "__main__":
    if sys.argv[1] == "history":
        history(sys.argv[2], sys.argv[3], sys.argv[4])
