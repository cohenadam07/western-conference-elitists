"""assemble.py — public/gm-savant.html from Coaching Savant's styles (so the two read as one tool), extra.css, body.html and app.js."""
import os, re
H = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(H, '..', '..', '..', '..'))
coach = open(os.path.join(ROOT, 'public', 'basketball-coaching-savant.html')).read()
css = re.search(r'<style>(.*?)</style>', coach, re.S).group(1)
css = re.sub(r"BASKETBALL COACHING SAVANT — (?:Basketball|NBA) Savant's page, for head coaches\.", "NBA GM SAVANT — styles copied from NBA Coaching Savant (itself NBA Savant's), so the pages read as one tool.", css)
head = '''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>NBA GM Savant — WCE Hoops</title>
<meta name="description" content="Every NBA general manager since 1979-80, judged like a fund manager: GM Value Added, every decision graded at the time and as it turned out, luck and shared credit kept apart."/>
<meta name="theme-color" content="#22395A"/>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Newsreader:opsz,wght@6..72,500;6..72,600&family=IBM+Plex+Mono:wght@400;500;600&family=IBM+Plex+Sans:wght@400;500;600;700&display=swap" rel="stylesheet">
'''
# Every number a refit can move is filled here from the build's own index (build_page.py writes it), never typed:
# {{value_per_margin_point}}, {{discount_implied_pct}}, ... A placeholder left unfilled stops the build.
import gzip, json
meta = json.loads(gzip.open(os.path.join(ROOT, 'public', 'gms', 'index.json.gz')).read())['meta']
FILL = {'value_per_margin_point': f"{meta['value_per_margin_point']:.1f}", 'points_per_win': f"{meta['points_per_win']}",
        'discount_implied_pct': f"{round(100 * meta['discount_implied'])}" if meta.get('discount_implied') is not None else 'no measurable',
        'discount_trades': str(meta.get('discount_trades', 0)), 'repeat_sentence': meta['repeat_sentence'],
        'first_curve_drafts': meta['first_pick_curve_drafts'], 'board_drafts': meta['board_drafts'], 'board_sources': meta['board_sources'],
        'lambda': f"{meta['titles']['lambda']:,.0f}", 'wins_per_title': f"{meta['titles']['wins_per_title']:.0f}",
        'title_seasons': meta['titles']['seasons'], 'title_skill': f"{meta['titles']['brier_skill_vs_best_record']:.0f}",
        **{f'cal_15_30_{k}': f'{v:g}' for k, v in next(b for b in meta['titles']['calibration'] if b['lo'] == 15).items() if k in ('teams', 'expected', 'won')}}


def fill(text, esc_json=False):
    for k, v in FILL.items():
        text = text.replace('{{' + k + '}}', json.dumps(v)[1:-1] if esc_json else v)
    left = re.findall(r'\{\{[a-z_]+\}\}', text)
    if left:
        raise SystemExit(f'unfilled placeholders: {sorted(set(left))}')
    return text


page = head + '<style>' + css + open(os.path.join(H, 'extra.css')).read() + '</style>\n<script src="/wce-nav.js" defer></script>\n</head>\n' + \
    fill(open(os.path.join(H, 'body.html')).read()) + '\n<script>\n' + 'const EXPL = ' + fill(open(os.path.join(H, 'explainers.json')).read().strip(), True) + ';\n' + \
    open(os.path.join(H, 'app.js')).read() + '</script>\n</body>\n</html>\n'
open(os.path.join(ROOT, 'public', 'gm-savant.html'), 'w').write(page)
# the review copy, from the same filled text the page carries (so what is read is what ships)
E = json.loads(fill(open(os.path.join(H, 'explainers.json')).read(), True))
md = ['# NBA GM Savant — every explainer, as the page shows it', '',
      'Each stat on the page has an "i" button that opens one of these (tap or click; Escape or a tap outside closes it). Four parts each: '
      'what it is, how it is calculated, the data behind it, and its limits. Numbers a refit can move are filled from the build, not typed. '
      'Generated by page/assemble.py.', '']
for k, e in E.items():
    md += [f"## {e['title']}", '', f"**What it is.** {e['what']}", '', f"**How it's calculated.** {e['how']}", '', f"**The data.** {e['data']}", '',
           f"**Limits.** {e['limits']}", '']
open(os.path.join(H, 'EXPLAINERS.md'), 'w').write('\n'.join(md))
print('public/gm-savant.html', len(page), 'bytes')
