"""
br_keep.py — a run without Basketball Reference keeps what the last good run had.

Everything Basketball Reference gives the season in progress comes from two pages, fetched
fresh on every run: the advanced table (br_fetch) and the play-by-play table (br_ext). Neither
has a fallback a runner can use: the cloud starts each run with no cache, so a refused request
used to mean these stats simply went missing from what was published:

    value bars     PER, WS/48, BPM, OBPM, DBPM, VORP, and defender difficulty, which needs DBPM
    play-by-play   the position estimate, and the three counts ESPN cannot stand in for
                   (offensive fouls drawn, own shots blocked, points generated by assists)

The run of Nov 1, 2026 published that way: BPM on 0 of 439 players, no position estimates, and
17 labels moved. So the last published copy is the fallback. It is carried per player, it is
never newer than the data around it, and the file says so: `stale` in savant-current.json.

Wired in refresh_current.py, before the labels and the passes that lean on DBPM. The published
files are read from SAVANT_PUBLIC, which cloud_refresh.py sets.

    python3 br_keep.py restore <dir holding the last good public/> [--public ../../public]

rewrites the published 2026-27 files from a last good copy, for a run that already went out.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

VALUE_KEYS = ("per", "ws48", "bpm", "obpm", "dbpm", "vorp")
BR_ONLY_KEYS = ("offd75", "blka", "pga75")      # br_fallback_pass has no ESPN version of these


def public_dir():
    return os.environ.get("SAVANT_PUBLIC") or os.path.join(HERE, "..", "..", "public")


def _read(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return None


def last_good(season, public=None):
    """The published copy of a season: {current: {id: row}, s: doc, panels: {id: panels}, generated}.
    Empty where a file is missing, or holds another season (the first run of a new one)."""
    public = public or public_dir()
    cur = _read(os.path.join(public, "savant-current.json")) or {}
    rows = {}
    if (cur.get("seasons") or [None])[0] == season:
        rows = {p["id"]: p for p in cur["data"][season]["players"]}
    s = _read(os.path.join(public, "savant-ext", "s", f"{season}.json")) or {}
    panels = _read(os.path.join(public, "savant-ext", "panels", f"{season}.json")) or {}
    return dict(current=rows, s=s, panels=panels.get("players") or {}, generated=cur.get("generated"))


def _has(p, key):
    return ((p.get("m", {}).get(key) or {}).get("season") or {}).get("v") is not None


def keep_value_bars(players, last):
    """Value bars from the last good run, for players this run has none for."""
    n = 0
    for p in players:
        if any(_has(p, k) for k in VALUE_KEYS):
            continue
        old = last["current"].get(p["id"])
        if not old:
            continue
        got = {k: old["m"][k] for k in VALUE_KEYS if _has(old, k)}
        if got:
            p["m"].update(got)
            n += 1
    return n


def _ext_cells(doc, pid, key):
    """{window: {"v","n"}} of one stat out of a savant-ext/s file."""
    keys = doc.get("keys") or []
    if key not in keys:
        return None
    i = keys.index(key)
    out = {}
    for w, row in (doc.get("players", {}).get(str(pid)) or {}).items():
        c = row[i] if row and i < len(row) else None
        if c:
            out[w] = {"v": c[0], "n": c[1]}
    return out or None


def keep_br_stats(players, last):
    """Position estimates and the Basketball-Reference-only counts from the last good run.
    An estimate is kept for whoever has none tonight; the counts only on a night the whole table
    is missing, because a player missing from a good table has no count to keep."""
    panels = last["panels"]
    table_missing = not any(p.get("pe") for p in players)
    kept = stats = 0
    for p in players:
        if not p.get("pe"):
            old = (panels.get(str(p["id"])) or {}).get("pe")
            if old and any(old):
                p["pe"] = old
                kept += 1
        if table_missing:
            moved = False
            for k in BR_ONLY_KEYS:
                if p.get("m", {}).get(k):
                    continue
                cells = _ext_cells(last["s"], p["id"], k)
                if cells:
                    p.setdefault("m", {})[k] = cells
                    moved = True
            stats += moved
    return kept, stats, table_missing


def restore(source, public):
    """Lay the last good copy under a published season whose Basketball Reference data is gone."""
    cur_path = os.path.join(public, "savant-current.json")
    d = json.load(open(cur_path))
    season = d["seasons"][0]
    players = d["data"][season]["players"]
    last = last_good(season, source)
    bars = keep_value_bars(players, last)
    ddiff = 0
    for p in players:
        old = last["current"].get(p["id"])
        if old and not _has(p, "ddiff") and _has(old, "ddiff"):
            p["m"]["ddiff"] = old["m"]["ddiff"]
            ddiff += 1
    s_path = os.path.join(public, "savant-ext", "s", f"{season}.json")
    pan_path = os.path.join(public, "savant-ext", "panels", f"{season}.json")
    s, pan = json.load(open(s_path)), json.load(open(pan_path))
    pes = 0
    for pid, row in pan["players"].items():
        old = (last["panels"].get(pid) or {}).get("pe")
        if old and any(old) and not row.get("pe"):
            row["pe"] = old
            pes += 1
    keys = s["keys"]
    cells = 0
    for pid, wins in s["players"].items():
        for k in BR_ONLY_KEYS:
            i = keys.index(k)
            for w, c in (_ext_cells(last["s"], pid, k) or {}).items():
                if w in wins and wins[w][i] is None:
                    wins[w][i] = [c["v"], c["n"]]
                    cells += 1
    json.dump(d, open(cur_path, "w"), separators=(",", ":"))
    json.dump(s, open(s_path, "w"), separators=(",", ":"))
    json.dump(pan, open(pan_path, "w"), separators=(",", ":"))
    print(f"{season}: value bars on {bars} players, defender difficulty on {ddiff}, "
          f"estimates on {pes}, {cells} Basketball Reference cells")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["restore"])
    ap.add_argument("source", help="a directory laid out like public/, holding the last good files")
    ap.add_argument("--public", default=os.path.join(HERE, "..", "..", "public"))
    a = ap.parse_args()
    return restore(a.source, a.public)


if __name__ == "__main__":
    sys.exit(main())
