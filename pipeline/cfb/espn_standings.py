"""Step 16 evidence. ESPN's 2026 conference standings for the Power 4, against records and
head-to-head results computed independently from game results.

    python -m pipeline.cfb.espn_standings

Writes research/cfb/out/standings_2026.md. This lays out evidence only; it does not adjudicate the
conferences' tiebreaker rulebooks.

Sources: ESPN standings endpoint (one call per league), the release schedule file
espn_cfb_schedules/cfb_schedule_2026.parquet for completed games, and the ESPN scoreboard by week
for the file's last week onward (cross-check plus the games still to play). All cached.
"""
import datetime as dt
from collections import Counter, defaultdict
from itertools import combinations

import pandas as pd

from .espn_http import CACHE, get_json, pmap
from .paths import RAW, OUT

SEASON = 2026
LEAGUES = {"ACC": 1, "Big 12": 4, "Big Ten": 5, "SEC": 8}
EXPECT = {1: "Atlantic Coast Conference", 4: "Big 12 Conference", 5: "Big Ten Conference",
          8: "Southeastern Conference"}
STANDINGS = ("https://site.api.espn.com/apis/v2/sports/football/college-football/standings"
             "?season={s}&group={g}")
SB_WEEK = ("https://site.api.espn.com/apis/site/v2/sports/football/college-football/scoreboard"
           "?groups=80&limit=400&seasontype=2&week={w}&dates={s}")
MAX_WEEK = 16
BEST_RULE = "head-to-head wins inside the tied group, then overall win pct, then alphabetical"


def wl(w, l):
    return f"{w}-{l}"


def pct(w, l):
    return w / (w + l) if (w + l) else 0.0


def load_games():
    """Completed games from the release file, topped up from the scoreboard; plus games still to play."""
    sch = pd.read_parquet(RAW / "espn_cfb_schedules" / f"cfb_schedule_{SEASON}.parquet")
    print("schedule columns:", list(sch.columns))
    print(f"schedule rows: {len(sch)}, status: {sch.status.value_counts().to_dict()}, "
          f"weeks {sch.week.min()}-{sch.week.max()}, last game {sch.game_date.max()}")
    done, names = {}, {}
    for r in sch.itertuples():
        names[r.home_id], names[r.away_id] = r.home_team, r.away_team
        if "FINAL" not in str(r.status).upper():
            continue
        done[int(r.game_id)] = dict(id=int(r.game_id), week=int(r.week), date=r.game_date[:10], home=int(r.home_id),
                                    away=int(r.away_id), hs=int(r.home_score), as_=int(r.away_score),
                                    conf=bool(r.conference_competition), src="release file")
    last_week = int(sch.week.max())
    weeks = list(range(last_week, MAX_WEEK + 1))
    boards = pmap(lambda w: get_json(SB_WEEK.format(w=w, s=SEASON), f"scoreboard_{SEASON}_wk{w}"), weeks)
    todo, notes = [], []
    checked = added = 0
    for w, sb in zip(weeks, boards):
        for e in sb.get("events", []):
            c = e["competitions"][0]
            side = {x["homeAway"]: x for x in c["competitors"]}
            h, a = side["home"], side["away"]
            for x in (h, a):
                names.setdefault(int(x["team"]["id"]), x["team"]["displayName"])
            g = dict(id=int(e["id"]), week=w, date=e["date"][:10], home=int(h["team"]["id"]),
                     away=int(a["team"]["id"]), conf=bool(c.get("conferenceCompetition")),
                     src=f"scoreboard week {w}")
            if e["status"]["type"].get("completed"):
                g["hs"], g["as_"] = int(h["score"]), int(a["score"])
                if g["id"] in done:
                    checked += 1
                    f = done[g["id"]]
                    if (f["hs"], f["as_"], f["conf"]) != (g["hs"], g["as_"], g["conf"]):
                        notes.append(f"game {g['id']}: release file {f['hs']}-{f['as_']} conf={f['conf']} vs "
                                     f"scoreboard {g['hs']}-{g['as_']} conf={g['conf']}")
                else:
                    done[g["id"]] = g
                    added += 1
            else:
                g["status"] = e["status"]["type"]["name"]
                todo.append(g)
    print(f"scoreboard weeks {weeks[0]}-{weeks[-1]}: {checked} finals cross-checked against the file, "
          f"{added} finals added, {len(todo)} games not yet final, {len(notes)} disagreements")
    return list(done.values()), todo, names, dict(last_week=last_week, checked=checked, added=added,
                                                  notes=notes, last_date=sch.game_date.max(),
                                                  n_file=len(sch))


def main():
    L = [f"# ESPN conference standings vs game results, {SEASON} Power 4 (step 16 evidence)", "",
         "Generated by `python -m pipeline.cfb.espn_standings`. Evidence only: nothing here applies a "
         "conference's tiebreaker rulebook.", ""]

    # ---- ESPN standings -------------------------------------------------------------------------
    raw = dict(zip(LEAGUES, pmap(lambda g: get_json(STANDINGS.format(s=SEASON, g=g),
                                                    f"standings_{SEASON}_g{g}"), LEAGUES.values())))
    fetched = dt.datetime.fromtimestamp((CACHE / f"standings_{SEASON}_g8.json.gz").stat().st_mtime)
    first = raw["SEC"]
    e0 = first["standings"]["entries"][0]
    print("standings keys:", list(first.keys()))
    print("standings.standings keys:", list(first["standings"].keys()))
    print("entry keys:", list(e0.keys()), "| team keys:", list(e0["team"].keys()))
    base_types = [s["type"] for s in e0["stats"] if "_" not in s["type"]]
    prefixes = sorted({s["type"].split("_")[0] for s in e0["stats"] if "_" in s["type"]})
    print("stat types (unprefixed):", base_types)
    print("stat type prefixes:", prefixes)
    L += ["## What the endpoint returns", "",
          f"`{STANDINGS.format(s=SEASON, g='{groupId}')}`, fetched {fetched:%Y-%m-%d %H:%M} local time.", "",
          f"- Top-level keys: `{', '.join(first.keys())}`; `standings` keys: "
          f"`{', '.join(first['standings'].keys())}`; each entry: `{', '.join(e0.keys())}`.",
          f"- Each entry has {len(e0['stats'])} stats. Names repeat, so they must be keyed by `type`. "
          f"Unprefixed types: `{', '.join(base_types)}`. The same block repeats with the prefixes "
          f"`{', '.join(prefixes)}`.",
          "- Order fields that exist: `playoffseed` (and `vsconf_playoffseed`), `gamesbehind`, "
          "`leaguewinpercent`, and `team.rank` (a national poll rank; the response does not say which poll). "
          "There is no stat called `rank` or `seed`, and the entries carry no explicit position other than "
          "their order in the list.",
          "- Records: `total` (`summary` = overall W-L) and `vsconf` (`summary` = conference W-L).", "",
          "| league | group id | name in response | entries | seasonType |", "|---|---|---|---|---|"]
    for lg, gid in LEAGUES.items():
        j = raw[lg]
        ok = j.get("name") == EXPECT[gid]
        print(f"group {gid}: {j.get('name')} ({j.get('shortName')}) {'OK' if ok else '!! unexpected name'}")
        L.append(f"| {lg} | {gid} | {j.get('name')} | {len(j['standings']['entries'])} | "
                 f"{j['standings'].get('seasonType')} |")
        if not ok:
            raise SystemExit(f"group {gid} is not {EXPECT[gid]}")
    L.append("")

    # one probe: does the endpoint honour a sort parameter?
    probe = get_json(STANDINGS.format(s=SEASON, g=8) + "&sort=playoffseed:asc", f"standings_{SEASON}_g8_sortseed")
    probe_order = [x["team"]["id"] for x in probe.get("standings", {}).get("entries", [])]

    games, todo, names, meta = load_games()

    L += ["## Game results used", "",
          f"- Release schedule file: {meta['n_file']} rows, all final, weeks 1-{meta['last_week']}, last kickoff "
          f"{meta['last_date']}.",
          f"- ESPN scoreboard, weeks {meta['last_week']}-{MAX_WEEK} (one call per week): {meta['checked']} finals "
          f"cross-checked against the file ({len(meta['notes'])} disagreements on score or conference flag), "
          f"{meta['added']} finals the file lacked, {len(todo)} games not yet played.",
          "- Dates below are the UTC date of kickoff, so a Saturday night game can show as Sunday.",
          "- A conference game is one where both teams are in the league's standings and ESPN's "
          "`conference_competition` flag is true. Same-league games with the flag false are listed per league.",
          ""]
    L += [f"- !! {n}" for n in meta["notes"]]

    team_games = defaultdict(list)
    for g in games:
        team_games[g["home"]].append(g)
        team_games[g["away"]].append(g)
    team_todo = defaultdict(list)
    for g in todo:
        team_todo[g["home"]].append(g)
        team_todo[g["away"]].append(g)

    def result(g, t):
        """(won, own score, opp score, opp id, 'vs'/'at') for team t in final game g."""
        if g["home"] == t:
            return g["hs"] > g["as_"], g["hs"], g["as_"], g["away"], "vs"
        return g["as_"] > g["hs"], g["as_"], g["hs"], g["home"], "at"

    key_tests = defaultdict(Counter)
    composite = {}
    fallback_overall, fallback_alpha = [], []
    all_flags_h2h, all_flags_unres, returned_tests, record_mismatch = [], [], [], []

    for lg, gid in LEAGUES.items():
        ent = raw[lg]["standings"]["entries"]
        T = {}
        for pos, x in enumerate(ent, 1):
            st = {s["type"]: s for s in x["stats"]}
            tid = int(x["team"]["id"])
            T[tid] = dict(id=tid, name=x["team"]["shortDisplayName"], full=x["team"]["displayName"], pos=pos,
                          seed=int(st["playoffseed"]["value"]), vseed=int(st["vsconf_playoffseed"]["value"]),
                          e_conf=st["vsconf"]["summary"], e_ovr=st["total"]["summary"],
                          rank=x["team"].get("rank"), e_lpct=st["leaguewinpercent"]["value"],
                          gb=st["gamesbehind"]["displayValue"],
                          e_cpd=st["vsconf_pointdifferential"]["value"], e_pd=st["pointdifferential"]["value"])
        mem = set(T)
        nonconf_same = []
        for t in T.values():
            cg = [g for g in team_games[t["id"]] if g["home"] in mem and g["away"] in mem]
            t["cg"] = sorted([g for g in cg if g["conf"]], key=lambda g: g["date"])
            nonconf_same += [g for g in cg if not g["conf"]]
            res = [result(g, t["id"]) for g in t["cg"]]
            t["cw"], t["cl"] = sum(r[0] for r in res), sum(not r[0] for r in res)
            t["cpd"] = sum(r[1] - r[2] for r in res)
            allr = [result(g, t["id"]) for g in team_games[t["id"]]]
            t["ow"], t["ol"] = sum(r[0] for r in allr), sum(not r[0] for r in allr)
            t["rem"] = sorted([g for g in team_todo[t["id"]] if g["home"] in mem and g["away"] in mem and g["conf"]],
                              key=lambda g: g["date"])
            t["rem_nc"] = [g for g in team_todo[t["id"]] if g["home"] in mem and g["away"] in mem and not g["conf"]]
            if wl(t["cw"], t["cl"]) != t["e_conf"] or wl(t["ow"], t["ol"]) != t["e_ovr"]:
                record_mismatch.append((lg, t["name"], wl(t["cw"], t["cl"]), t["e_conf"],
                                        wl(t["ow"], t["ol"]), t["e_ovr"]))
        for t in T.values():
            opp = [result(g, t["id"])[3] for g in t["cg"]]
            t["opp_w"], t["opp_l"] = sum(T[o]["cw"] for o in opp), sum(T[o]["cl"] for o in opp)
            ropp = [g["away"] if g["home"] == t["id"] else g["home"] for g in t["rem"]]
            t["allopp_w"] = t["opp_w"] + sum(T[o]["cw"] for o in ropp)
            t["allopp_l"] = t["opp_l"] + sum(T[o]["cl"] for o in ropp)
            t["opp_ids"] = opp

        def h2h(a, b):
            """Conference games between a and b: list of (winner id, text)."""
            out = []
            for g in T[a]["cg"]:
                if b in (g["home"], g["away"]):
                    won, s1, s2, _, ha = result(g, a)
                    w, l_ = (a, b) if won else (b, a)
                    out.append((w, f"{T[w]['name']} {max(s1, s2)}, {T[l_]['name']} {min(s1, s2)} "
                                   f"({g['date']}, at {T[g['home']]['name']})"))
            return out

        L += [f"## {lg}", ""]
        # ---- ESPN order -----------------------------------------------------------------------
        L += ["### ESPN's order, and the records computed from game results", "",
              "`pos` = position in the list as returned. `seed` = ESPN's `playoffseed` stat.", "",
              "| pos | seed | team | ESPN conf | ESPN overall | computed conf | computed overall | conf pct | "
              "conf pt diff | poll rank | conf games left |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for t in sorted(T.values(), key=lambda t: t["pos"]):
            flag = "" if (wl(t["cw"], t["cl"]) == t["e_conf"] and wl(t["ow"], t["ol"]) == t["e_ovr"]) else " !!"
            L.append(f"| {t['pos']} | {t['seed']} | {t['name']} | {t['e_conf']} | {t['e_ovr']} | "
                     f"{wl(t['cw'], t['cl'])}{flag} | {wl(t['ow'], t['ol'])} | {pct(t['cw'], t['cl']):.3f} | "
                     f"{t['cpd']:+d} | {t['rank'] or ''} | {len(t['rem'])} |")
        L.append("")
        seeds_same = all(t["seed"] == t["vseed"] for t in T.values())
        by_seed = sorted(T.values(), key=lambda t: t["seed"])
        L += ["Order by `playoffseed`: " + ", ".join(f"{t['seed']}. {t['name']} ({t['e_conf']})" for t in by_seed)
              + ".", "",
              f"`playoffseed` equals `vsconf_playoffseed` for every team: {seeds_same}. Seeds are "
              f"{'a clean 1..n with no repeats' if sorted(t['seed'] for t in T.values()) == list(range(1, len(T) + 1)) else 'NOT a clean 1..n'}.",
              ""]
        if nonconf_same or any(t["rem_nc"] for t in T.values()):
            seen = {g["id"]: g for g in nonconf_same}
            seen.update({g["id"]: g for t in T.values() for g in t["rem_nc"]})
            L += ["Games between two league members that ESPN flags as non-conference (excluded from "
                  "conference records and head-to-head here):", ""]
            for g in sorted(seen.values(), key=lambda g: g["date"]):
                sc = f"{g['as_']}-{g['hs']}" if "hs" in g else "not played"
                L.append(f"- {g['date']}: {T[g['away']]['name']} at {T[g['home']]['name']}, {sc} (game {g['id']})")
            L.append("")

        # ---- what the as-returned order is sorted by --------------------------------------------
        guess = sorted(T.values(), key=lambda t: (-pct(*map(int, t["e_ovr"].split("-"))), t["seed"]))
        ok_ret = [t["id"] for t in guess] == [t["id"] for t in sorted(T.values(), key=lambda t: t["pos"])]
        returned_tests.append((lg, ok_ret))
        seed_mono = all(pct(a["cw"], a["cl"]) >= pct(b["cw"], b["cl"]) - 1e-12
                        for a, b in zip(by_seed, by_seed[1:]))
        wins_mono = all(a["cw"] >= b["cw"] for a, b in zip(by_seed, by_seed[1:]))
        L += [f"- As-returned order equals a sort by overall win pct (descending) then `playoffseed`: **{ok_ret}**.",
              f"- `playoffseed` never puts a lower conference win pct above a higher one: **{seed_mono}** "
              f"(conference wins alone {'are also monotone here, so this league cannot tell pct from wins' if wins_mono else 'are not monotone, so the key is pct, not wins'}).",
              ""]

        # ---- composite rules: can a simple procedure reproduce every seed? ----------------------------
        def mini(ids):
            rec = {i: [0, 0] for i in ids}
            for a, b in combinations(ids, 2):
                for w, _ in h2h(a, b):
                    rec[w][0] += 1
                    rec[b if w == a else a][1] += 1
            return rec

        def order(ids, h2h_key, fallback, track=None):
            if len(ids) == 1:
                return list(ids)
            if h2h_key:
                rec = mini(ids)
                parts = defaultdict(list)
                for i in ids:
                    parts[h2h_key(*rec[i])].append(i)
                if len(parts) > 1:
                    out = []
                    for k in sorted(parts, reverse=True):
                        out += order(parts[k], h2h_key, fallback, track)
                    return out
            if track is not None and len(ids) > 1:
                track.append(ids)
            return sorted(ids, key=fallback)

        ovr = lambda i: -pct(T[i]["ow"], T[i]["ol"])                      # noqa: E731
        alpha = lambda i: T[i]["full"]                                    # noqa: E731
        rank = lambda i: T[i]["rank"] or 999                              # noqa: E731
        rules = {
            "overall win pct, then alphabetical": (None, lambda i: (ovr(i), alpha(i))),
            "head-to-head wins inside the tied group, then overall win pct, then alphabetical":
                (lambda w, l: w, lambda i: (ovr(i), alpha(i))),
            "head-to-head win pct inside the tied group, then overall win pct, then alphabetical":
                (lambda w, l: pct(w, l), lambda i: (ovr(i), alpha(i))),
            "head-to-head wins minus losses inside the tied group, then overall win pct, then alphabetical":
                (lambda w, l: w - l, lambda i: (ovr(i), alpha(i))),
            "head-to-head wins inside the tied group, then poll rank, then alphabetical":
                (lambda w, l: w, lambda i: (rank(i), alpha(i))),
            "head-to-head wins inside the tied group, then alphabetical":
                (lambda w, l: w, alpha),
            "head-to-head wins inside the tied group, then conference point differential":
                (lambda w, l: w, lambda i: -T[i]["cpd"]),
        }
        pgroups = defaultdict(list)
        for t in T.values():
            pgroups[round(pct(t["cw"], t["cl"]), 9)].append(t["id"])
        for label, (hk, fb) in rules.items():
            pred = []
            track = [] if label == BEST_RULE else None
            for k in sorted(pgroups, reverse=True):
                pred += order(pgroups[k], hk, fb, track)
            for ids in track or []:
                by_ovr = defaultdict(list)
                for i in ids:
                    by_ovr[(T[i]["ow"], T[i]["ol"])].append(i)
                fallback_overall.append((lg, [T[i]["name"] for i in sorted(ids, key=lambda i: T[i]["seed"])]))
                for rec_, same in by_ovr.items():
                    if len(same) > 1:
                        fallback_alpha.append((lg, wl(*rec_), [T[i]["name"] for i in sorted(same, key=lambda i: T[i]["seed"])]))
            hit = sum(T[i]["seed"] == n for n, i in enumerate(pred, 1))
            c = composite.setdefault(label, [0, []])
            c[0] += hit
            if hit == len(T):
                c[1].append(lg)

        # ---- tied sets, league-wide ---------------------------------------------------------------
        groups = defaultdict(list)
        for t in by_seed:
            groups[(t["cw"], t["cl"])].append(t)

        # candidate secondary keys, tested on every pair inside an identical-record group
        for rec, grp in groups.items():
            for hi, lo in combinations(grp, 2):      # hi has the better ESPN seed
                def vote(name, a, b):                 # a, b: larger is better
                    key_tests[name]["agree" if a > b else "contradict" if a < b else "no information"] += 1
                hh = h2h(hi["id"], lo["id"])
                if hh:
                    w = Counter(x[0] for x in hh)
                    vote("head-to-head winner first", w[hi["id"]], w[lo["id"]])
                else:
                    key_tests["head-to-head winner first"]["no information"] += 1
                vote("overall win pct", pct(hi["ow"], hi["ol"]), pct(lo["ow"], lo["ol"]))
                vote("conference point differential", hi["cpd"], lo["cpd"])
                vote("overall point differential", hi["e_pd"], lo["e_pd"])
                vote("poll rank (unranked last)", -(hi["rank"] or 999), -(lo["rank"] or 999))
                vote("opponents' conference win pct (played)", pct(hi["opp_w"], hi["opp_l"]),
                     pct(lo["opp_w"], lo["opp_l"]))
                vote("alphabetical by display name", lo["full"], hi["full"])
                common = (set(hi["opp_ids"]) & set(lo["opp_ids"])) - {hi["id"], lo["id"]}

                def vs(t):
                    r = [result(g, t["id"]) for g in t["cg"]]
                    return pct(sum(x[0] for x in r if x[3] in common), sum(not x[0] for x in r if x[3] in common))
                if common:
                    vote("record vs common conference opponents", vs(hi), vs(lo))
                else:
                    key_tests["record vs common conference opponents"]["no information"] += 1

        def tied_set_report(grp, lines):
            """Evidence block for one identical-record set. Returns (pairwise flags, unresolved flag)."""
            ids = [t["id"] for t in grp]
            rec = wl(grp[0]["cw"], grp[0]["cl"])
            label = ", ".join(f"{t['name']} (seed {t['seed']}, pos {t['pos']})" for t in grp)
            lines += [f"**Tied at {rec}: {label}**", ""]
            mini = {i: [0, 0] for i in ids}
            played, unplayed, contradictions = [], [], []
            for a, b in combinations(grp, 2):
                hh = h2h(a["id"], b["id"])
                if not hh:
                    later = [g for g in a["rem"] if b["id"] in (g["home"], g["away"])]
                    unplayed.append(f"{a['name']} and {b['name']}" +
                                    (f" (meet {later[0]['date']})" if later else " (do not meet)"))
                    continue
                for w, txt in hh:
                    lo_ = b["id"] if w == a["id"] else a["id"]
                    mini[w][0] += 1
                    mini[lo_][1] += 1
                    played.append(txt)
                    for field, nm in (("seed", "playoffseed"), ("pos", "as-returned order")):
                        if T[lo_][field] < T[w][field]:
                            contradictions.append((lg, rec, T[w]["name"], T[lo_]["name"], nm, txt))
            lines += ["- Head-to-head games: " + ("; ".join(played) if played else "none played") + "."]
            if unplayed:
                lines += ["- Pairs with no game yet: " + "; ".join(unplayed) + "."]
            if len(grp) > 2:
                lines += ["- Head-to-head record inside the tied set: " +
                          ", ".join(f"{T[i]['name']} {wl(*mini[i])}" for i in ids) + "."]
            common = set.intersection(*[set(t["opp_ids"]) for t in grp]) - set(ids)
            if common:
                parts = []
                for t in grp:
                    r = [result(g, t["id"]) for g in t["cg"]]
                    parts.append(f"{t['name']} {wl(sum(x[0] for x in r if x[3] in common), sum(not x[0] for x in r if x[3] in common))}")
                lines += [f"- Common conference opponents played by all ({len(common)}: "
                          f"{', '.join(sorted(T[o]['name'] for o in common))}): " + ", ".join(parts) + "."]
            else:
                lines += ["- Common conference opponents played by all: none."]
            n_pairs = len(grp) * (len(grp) - 1) // 2
            complete = not unplayed
            wins = sorted((mini[i][0] for i in ids), reverse=True)
            strict = complete and len(set(wins)) == len(wins)
            h2h_order = [T[i]["name"] for i in sorted(ids, key=lambda i: -mini[i][0])] if strict else None
            espn_order = [t["name"] for t in sorted(grp, key=lambda t: t["seed"])]
            unresolved = None
            if strict:
                same = h2h_order == espn_order
                lines += [f"- Head-to-head alone gives a full order ({' > '.join(h2h_order)}); ESPN's seed order "
                          f"is {' > '.join(espn_order)}: {'same' if same else '**DIFFERENT**'}."]
            else:
                why = (f"only {n_pairs - len(unplayed)} of {n_pairs} pairs have played" if unplayed
                       else "the head-to-head records inside the set are not all different")
                lines += [f"- **Head-to-head alone cannot order this set** ({why}), yet ESPN seeds them "
                          f"{' > '.join(espn_order)}."]
                unresolved = (lg, rec, espn_order, why)
            lines.append("")
            return contradictions, unresolved

        # ---- top three (plus ties with third) ---------------------------------------------------------
