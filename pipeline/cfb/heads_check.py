"""Report item 7. Headshot coverage for the 2026 rosters of ten FBS teams across conference tiers.

HEAD-checks https://a.espncdn.com/i/headshots/college-football/players/full/{athleteId}.png for every
player on the release roster file, at most 6 in parallel, and caches the answers in
~/College-Football-Savant/raw/espn_live/headshots_2026.json so a rerun makes no calls.

    python -m pipeline.cfb.heads_check
"""
import json
from collections import Counter

import pandas as pd

from .espn_http import CACHE, head_status, pmap
from .paths import RAW, OUT

URL = "https://a.espncdn.com/i/headshots/college-football/players/full/{}.png"
CACHE_FILE = CACHE / "headshots_2026.json"
TEAMS = {194: "Ohio State", 61: "Georgia", 2641: "Texas Tech", 228: "Clemson", 87: "Notre Dame",
         68: "Boise State", 2655: "Tulane", 256: "James Madison", 2649: "Toledo", 338: "Kennesaw State"}
GROUPS = {"QB/RB/WR/TE": {"QB", "RB", "FB", "WR", "TE"},
          "OL": {"OL", "OT", "G", "C"},
          "defense": {"DL", "DE", "DT", "NT", "EDGE", "LB", "DB", "CB", "S"},
          "specialists": {"PK", "P", "LS", "PR"}}


def group_of(pos):
    for g, s in GROUPS.items():
        if pos in s:
            return g
    return "other"


def pct(x):
    return "n/a" if pd.isna(x) else f"{100 * x:.1f}%"


def main():
    cols = ["team_id", "athlete_id", "position_abbreviation", "headshot_href", "team_display_name",
            "display_name", "division"]
    ro = pd.read_parquet(RAW / "espn_cfb_rosters" / "cfb_rosters_2026.parquet", columns=cols)
    print("roster columns used:", list(ro.columns), "| rows:", len(ro))
    conf = pd.read_parquet(RAW / "espn_cfb_teams" / "cfb_teams_2026.parquet",
                           columns=["team_id", "conference_short_name", "is_fbs"]).set_index("team_id")
    for tid, want in TEAMS.items():
        names = ro.loc[ro.team_id == tid, "team_display_name"].unique().tolist()
        ok = len(names) == 1 and names[0].startswith(want)
        print(f"team {tid}: expected {want!r}, roster file says {names} "
              f"({conf.conference_short_name.get(tid)}, is_fbs={conf.is_fbs.get(tid)}) {'OK' if ok else '!! MISMATCH'}")
        if not ok:
            raise SystemExit(f"team id {tid} does not map to {want}")
    t = ro[ro.team_id.isin(TEAMS)].drop_duplicates(["team_id", "athlete_id"]).copy()

    cache = json.loads(CACHE_FILE.read_text()) if CACHE_FILE.exists() else {}
    todo = [int(a) for a in t.athlete_id if str(int(a)) not in cache]
    print(f"{len(t)} players, {len(cache)} cached, {len(todo)} to HEAD")
    if todo:
        res = pmap(lambda a: head_status(URL.format(a)), todo)
        for a, (st, ct, ln) in zip(todo, res):
            if isinstance(st, int):          # never cache a network error as an answer
                cache[str(a)] = [st, ct, ln]
        CACHE_FILE.write_text(json.dumps(cache))
    t["status"] = [cache.get(str(int(a)), [None])[0] for a in t.athlete_id]
    t["ctype"] = [cache.get(str(int(a)), [None, None])[1] for a in t.athlete_id]
    t["length"] = [cache.get(str(int(a)), [None, None, None])[2] for a in t.athlete_id]
    t["ok"] = (t.status == 200) & t.ctype.fillna("").str.startswith("image/")
    t["href"] = t.headshot_href.notna()
    t["group"] = t.position_abbreviation.map(group_of)
    print("status counts:", t.status.value_counts(dropna=False).to_dict())
    print("content types of 200s:", t.loc[t.status == 200, "ctype"].value_counts().to_dict())

    L = ["# Headshot coverage, 2026 rosters, ten FBS teams (report item 7)", "",
         "Generated by `python -m pipeline.cfb.heads_check`. One HEAD per player on "
         "`https://a.espncdn.com/i/headshots/college-football/players/full/{athleteId}.png`; a hit is "
         "HTTP 200 with an `image/*` content type (a miss is a 404 `text/html` of length 1). Rosters: "
         "`espn_cfb_rosters/cfb_rosters_2026.parquet`. All ten team ids were checked against the roster "
         "file's `team_display_name`.", "",
         "| team (id) | conference | roster | HTTP 200 | QB/RB/WR/TE | OL | defense | specialists | "
         "roster file `headshot_href` non-null |", "|---|---|---|---|---|---|---|---|---|"]

    def row(label, cf, d):
        g = d.groupby("group").ok.agg(["mean", "size"])
        cells = [f"{pct(g['mean'].get(k, float('nan')))} ({int(g['size'].get(k, 0))})" for k in GROUPS]
        return (f"| {label} | {cf} | {len(d)} | {pct(d.ok.mean())} | " + " | ".join(cells) +
                f" | {pct(d.href.mean())} |")

    for tid, name in TEAMS.items():
        d = t[t.team_id == tid]
        L.append(row(f"{name} ({tid})", conf.conference_short_name.get(tid), d))
    L.append(row("**All ten**", "", t))
    other = t[t.group == "other"]
    L += ["", f"Cells are share with a headshot (players in the group). {len(other)} player(s) with a position "
          f"outside the four groups ({', '.join(sorted(other.position_abbreviation.unique())) or 'none'}) count "
          "in the roster total only.", ""]

    # does the roster file's own field predict the 200s?
    tp = int((t.href & t.ok).sum()); fp = int((t.href & ~t.ok).sum())
    fn = int((~t.href & t.ok).sum()); tn = int((~t.href & ~t.ok).sum())
    L += ["## Does the roster file's `headshot_href` predict the 200s?", "",
          "| | HTTP 200 | not 200 |", "|---|---|---|",
          f"| `headshot_href` present | {tp} | {fp} |", f"| `headshot_href` null | {fn} | {tn} |", "",
          f"- `headshot_href` non-null for {pct(t.href.mean())} of the {len(t)} players "
          f"(whole 2026 roster file: {pct(ro.headshot_href.notna().mean())} of {len(ro)} rows; "
          f"FBS rows {pct(ro.loc[ro.division == 'fbs', 'headshot_href'].notna().mean())} of "
          f"{int((ro.division == 'fbs').sum())}; FCS rows "
          f"{pct(ro.loc[ro.division == 'fcs', 'headshot_href'].notna().mean())}).",
          f"- Agreement with the HEAD check: {pct((t.href == t.ok).mean())} "
          f"({tp + tn} of {len(t)}). When the field is present the image exists "
          f"{pct(tp / (tp + fp) if tp + fp else float('nan'))} of the time; when it is null the image is "
          f"missing {pct(tn / (tn + fn) if tn + fn else float('nan'))} of the time.",
          f"- Every non-null `headshot_href` is exactly the standard URL for that athlete id: "
          f"{bool((t.loc[t.href, 'headshot_href'] == t.loc[t.href, 'athlete_id'].map(lambda a: URL.format(int(a)))).all())}.",
          ""]
    by_team = t.groupby("team_id").apply(lambda d: pd.Series({"href present, 404": int((d.href & ~d.ok).sum()),
                                                               "href null, 200": int((~d.href & d.ok).sum())}),
                                         include_groups=False)
    L += ["Disagreements by team:", "", "| team | href present but 404 | href null but 200 |", "|---|---|---|"]
    for tid, name in TEAMS.items():
        L.append(f"| {name} | {by_team.loc[tid, 'href present, 404']} | {by_team.loc[tid, 'href null, 200']} |")
    lens = Counter(t.loc[t.ok, "length"])
    top_len, top_n = lens.most_common(1)[0] if lens else (None, 0)
    L += ["", "## Notes", "",
          f"- Placeholder check: the {int(t.ok.sum())} hits have {len(lens)} distinct `Content-Length` values; "
          f"the most common length is shared by {top_n} image(s). A generic silhouette served with a 200 "
          "would show up as one length shared by many players.",
          f"- Status codes seen: {t.status.value_counts(dropna=False).to_dict()}.",
          f"- Calls: one HEAD per player, {len(t)} in total, cached in `{CACHE_FILE.name}`; "
          "at most 6 in flight.", ""]
    (OUT / "headshots.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[4:18]))
    print("wrote", OUT / "headshots.md")


if __name__ == "__main__":
    main()
